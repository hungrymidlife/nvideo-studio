-- Run against a dedicated Neon branch before applying to production.
-- App user IDs are the existing neon_auth.user UUIDs. No auth data is duplicated.
BEGIN;
CREATE SCHEMA IF NOT EXISTS nvideo_board;
CREATE TABLE IF NOT EXISTS nvideo_board.posts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 author_id uuid NOT NULL REFERENCES neon_auth."user"(id) ON DELETE CASCADE,
 category varchar(20) NOT NULL CHECK(category IN ('feedback','question','suggestion')),
 title varchar(140) NOT NULL CHECK(length(trim(title))>0),
 body text NOT NULL CHECK(length(trim(body))>0 AND length(body)<=12000),
 images jsonb NOT NULL DEFAULT '[]'::jsonb CHECK(jsonb_typeof(images)='array' AND jsonb_array_length(images)<=3),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 deleted_at timestamptz,
 hidden_at timestamptz
);
CREATE INDEX IF NOT EXISTS nvideo_board_posts_visible_idx
 ON nvideo_board.posts(id DESC) WHERE deleted_at IS NULL AND hidden_at IS NULL;
CREATE INDEX IF NOT EXISTS nvideo_board_posts_author_idx
 ON nvideo_board.posts(author_id,created_at DESC);
CREATE TABLE IF NOT EXISTS nvideo_board.reports (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 post_id bigint NOT NULL REFERENCES nvideo_board.posts(id) ON DELETE CASCADE,
 reporter_id uuid NOT NULL REFERENCES neon_auth."user"(id) ON DELETE CASCADE,
 reason varchar(200) NOT NULL CHECK(length(trim(reason))>0),
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(post_id,reporter_id)
);
CREATE INDEX IF NOT EXISTS nvideo_board_reports_created_idx ON nvideo_board.reports(created_at DESC);
COMMIT;
